class QuestionSerializer(serializers.ModelSerializer):
    """A question with its vote count. `voter` is write-only and optional (see voters.py)."""

    lecture_id = serializers.IntegerField(read_only=True)
    lecture_code = serializers.CharField(source="lecture.code", read_only=True)
    author = serializers.CharField(
        max_length=MAX_AUTHOR, required=False, allow_blank=True, default="", help_text="Empty = Anonymous"
    )
    votes = serializers.IntegerField(read_only=True, default=0, help_text="Number of upvotes")
    voted = serializers.BooleanField(read_only=True, default=False, help_text="Whether the calling voter has upvoted it")
    voter = serializers.CharField(
        max_length=MAX_VOTER, required=False, allow_blank=True, write_only=True,
        help_text="Optional explicit voter id; otherwise the `voter` cookie is used (and created)",
    )

    class Meta:
        model = Question
        fields = [
            "id", "lecture_id", "lecture_code", "text", "author", "votes", "voted", "is_answered", "created_at", "voter",
        ]
        read_only_fields = ["id", "created_at"]
        extra_kwargs = {"text": {"max_length": MAX_TEXT, "help_text": f"1–{MAX_TEXT} characters"}}

    def validate_text(self, value: str) -> str:
        value = collapse_whitespace(value)
        if not value:
            raise serializers.ValidationError("This field may not be blank.")
        return value

    def validate_author(self, value: str) -> str:
        return collapse_whitespace(value)

    def to_representation(self, question: Question) -> dict:
        data = super().to_representation(question)
        if not data["author"]:
            data["author"] = "Anonymous"
        return data

    def create(self, validated_data: dict) -> Question:
        validated_data.pop("voter", None)  # not a model field: consumed by the view
        return super().create(validated_data)

    def update(self, question: Question, validated_data: dict) -> Question:
        validated_data.pop("voter", None)
        return super().update(question, validated_data)


class LectureDetailSerializer(LectureSerializer):
    """GET /api/lectures/{key}/: the lecture plus its questions in screen order."""

    questions = QuestionSerializer(many=True, read_only=True, source="ordered_questions")

    class Meta(LectureSerializer.Meta):
        fields = LectureSerializer.Meta.fields + ["questions"]


