from rest_framework import serializers

from .models import HuntLog, WantedCriminal


class CoordinatesSerializer(serializers.Serializer):
    latitude = serializers.DecimalField(max_digits=9, decimal_places=6)
    longitude = serializers.DecimalField(max_digits=9, decimal_places=6)


class WantedCriminalSerializer(serializers.ModelSerializer):
    last_known_coordinates = serializers.SerializerMethodField(help_text="{latitude, longitude} or null when unknown")
    hunt_count = serializers.IntegerField(read_only=True, help_text="Number of journal entries for this criminal")

    class Meta:
        model = WantedCriminal
        fields = [
            "id", "name", "nickname", "reward", "last_known_coordinates", "location_note", "difficulty",
            "armed", "has_crew", "escape_master", "hunt_count",
        ]

    def get_last_known_coordinates(self, obj):
        if obj.latitude is None or obj.longitude is None:
            return None
        return {"latitude": obj.latitude, "longitude": obj.longitude}


class HuntLogSerializer(serializers.ModelSerializer):
    # The client sends criminal_id; it must reference an existing criminal (otherwise 400 "Invalid pk")
    criminal_id = serializers.PrimaryKeyRelatedField(source="criminal", queryset=WantedCriminal.objects.all())
    criminal_nickname = serializers.CharField(source="criminal.nickname", read_only=True)

    class Meta:
        model = HuntLog
        fields = ["id", "criminal_id", "criminal_nickname", "success", "notes", "created_at"]
        read_only_fields = ["id", "created_at"]  # created_at is generated by the server

    def validate_notes(self, value: str) -> str:
        return value.strip()
