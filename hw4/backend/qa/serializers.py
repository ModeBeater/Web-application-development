"""
Serializers: the contract between the JSON on the wire and the models.

A serializer declares which fields exist, which of them are read-only, how
input is validated (`validate_<field>`), and how a model row is turned into
JSON. Permission-derived flags (`can_manage`, `can_edit`) are computed per
request so the frontend can show or hide controls without guessing.
"""

from drf_spectacular.types import OpenApiTypes
from drf_spectacular.utils import extend_schema_field
from rest_framework import serializers

from accounts.serializers import UserPublicSerializer

from .links import join_url, screen_url
from .models import Lecture, Question
from .permissions import can_edit_question, can_manage_lecture

MAX_TITLE = 120
MIN_TITLE = 3
MAX_TEXT = 500


def collapse_whitespace(value: str) -> str:
    """'  Lecture   one ' -> 'Lecture one'."""
    return " ".join(value.split())


# ---------------------------------------------------------------------------
# Lectures
# ---------------------------------------------------------------------------


class LectureSerializer(serializers.ModelSerializer):
    """A lecture as the API shows it. `code`, `owner`, `created_at` and the URLs are read-only."""

    code = serializers.CharField(read_only=True, help_text="6-character join code generated by the server")
    owner = UserPublicSerializer(read_only=True)
    question_count = serializers.SerializerMethodField()
    join_url = serializers.SerializerMethodField(help_text="Address encoded in the QR code")
    screen_url = serializers.SerializerMethodField(help_text="Projector page")
    can_manage = serializers.SerializerMethodField(help_text="Whether the caller may edit, close or delete it")

    class Meta:
        model = Lecture
        fields = [
            "id", "title", "code", "is_open", "owner", "question_count", "created_at",
            "join_url", "screen_url", "can_manage",
        ]
        read_only_fields = ["id", "created_at"]
        extra_kwargs = {
            "title": {"max_length": MAX_TITLE, "help_text": f"{MIN_TITLE}–{MAX_TITLE} characters"},
            "is_open": {"help_text": "Closed lectures reject new questions with 409"},
        }

    def validate_title(self, value: str) -> str:
        value = collapse_whitespace(value)
        if len(value) < MIN_TITLE:
            raise serializers.ValidationError(f"Title must be at least {MIN_TITLE} characters.")
        return value

    def get_question_count(self, lecture: Lecture) -> int:
        annotated = getattr(lecture, "question_count", None)  # set by the viewset's queryset
        return annotated if annotated is not None else lecture.questions.count()

    @extend_schema_field(OpenApiTypes.URI)
    def get_join_url(self, lecture: Lecture) -> str:
        return join_url(self.context["request"], lecture)

    @extend_schema_field(OpenApiTypes.URI)
    def get_screen_url(self, lecture: Lecture) -> str:
        return screen_url(self.context["request"], lecture)

    def get_can_manage(self, lecture: Lecture) -> bool:
        return can_manage_lecture(self.context["request"].user, lecture)


