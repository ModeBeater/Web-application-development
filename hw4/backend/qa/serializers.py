class QuestionSerializer(serializers.ModelSerializer):
    """A question with its author and vote count."""

    lecture_id = serializers.IntegerField(read_only=True)
    lecture_code = serializers.CharField(source="lecture.code", read_only=True)
    lecture_title = serializers.CharField(source="lecture.title", read_only=True)
    author = UserPublicSerializer(read_only=True)
    votes = serializers.IntegerField(read_only=True, default=0, help_text="Number of upvotes")
    voted = serializers.BooleanField(read_only=True, default=False, help_text="Whether the caller has upvoted it")
    can_edit = serializers.SerializerMethodField(help_text="Whether the caller may edit or delete it")
    can_answer = serializers.SerializerMethodField(help_text="Whether the caller may mark it answered")

    class Meta:
        model = Question
        fields = [
            "id", "lecture_id", "lecture_code", "lecture_title", "text", "author", "votes", "voted",
            "is_answered", "created_at", "can_edit", "can_answer",
        ]
        read_only_fields = ["id", "created_at"]
        extra_kwargs = {"text": {"max_length": MAX_TEXT, "help_text": f"1–{MAX_TEXT} characters"}}

    def validate_text(self, value: str) -> str:
        value = collapse_whitespace(value)
        if not value:
            raise serializers.ValidationError("This field may not be blank.")
        return value

    def validate_is_answered(self, value: bool) -> bool:
        # Only the lecture owner / admin may change the answered flag through an update
        if self.instance is not None and value != self.instance.is_answered:
            if not can_manage_lecture(self.context["request"].user, self.instance.lecture):
                raise serializers.ValidationError("Only the lecture owner or an admin can change this.")
        return value

    def get_can_edit(self, question: Question) -> bool:
        return can_edit_question(self.context["request"].user, question)

    def get_can_answer(self, question: Question) -> bool:
        return can_manage_lecture(self.context["request"].user, question.lecture)


class LectureDetailSerializer(LectureSerializer):
    """GET /api/lectures/{key}/: the lecture plus its questions in screen order."""

    questions = QuestionSerializer(many=True, read_only=True, source="ordered_questions")

    class Meta(LectureSerializer.Meta):
        fields = LectureSerializer.Meta.fields + ["questions"]


