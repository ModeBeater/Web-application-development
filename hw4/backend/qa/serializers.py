class TopicSerializer(serializers.ModelSerializer):
    """A sub-topic of a lecture. `lecture_id` comes from the URL on create and is read-only afterwards."""

    lecture_id = serializers.IntegerField(read_only=True)
    lecture_code = serializers.CharField(source="lecture.code", read_only=True)
    question_count = serializers.IntegerField(read_only=True, default=0)

    class Meta:
        model = Topic
        fields = [
            "id", "lecture_id", "lecture_code", "title", "keywords", "description", "order", "question_count", "created_at",
        ]
        read_only_fields = ["id", "created_at"]
        extra_kwargs = {
            "title": {"max_length": MAX_TITLE, "help_text": f"{MIN_TITLE}–{MAX_TITLE} characters, unique within the lecture"},
            "keywords": {"max_length": MAX_KEYWORDS, "help_text": "Comma-separated hints used by the tagging model"},
            "description": {"help_text": "What the topic covers; the section text when extracted from the material"},
        }

    def validate_title(self, value: str) -> str:
        value = collapse_whitespace(value)
        if len(value) < MIN_TITLE:
            raise serializers.ValidationError(f"Title must be at least {MIN_TITLE} characters.")
        return value

    def validate_keywords(self, value: str) -> str:
        words = [collapse_whitespace(word).lower() for word in value.split(",")]
        return ", ".join(word for word in words if word)

    def validate(self, attrs: dict) -> dict:
        """(lecture, title) is unique — report it as a field error instead of a 500 from the database."""
        lecture = self.context.get("lecture") or getattr(self.instance, "lecture", None)
        title = attrs.get("title", getattr(self.instance, "title", None))
        if lecture is not None and title is not None:
            clash = Topic.objects.filter(lecture=lecture, title__iexact=title)
            if self.instance is not None:
                clash = clash.exclude(pk=self.instance.pk)
            if clash.exists():
                raise serializers.ValidationError({"title": ["This lecture already has a topic with that title."]})
        return attrs


class MaterialSerializer(serializers.ModelSerializer):
    """The uploaded lecture text. `text` is accepted as JSON or as a file field named `file` (txt / md / pdf)."""

    lecture_id = serializers.IntegerField(read_only=True)
    uploaded_by = UserPublicSerializer(read_only=True)
    characters = serializers.SerializerMethodField()

    class Meta:
        model = LectureMaterial
        fields = ["id", "lecture_id", "title", "text", "characters", "uploaded_by", "created_at", "updated_at"]
        read_only_fields = ["id", "created_at", "updated_at"]
        extra_kwargs = {"title": {"required": False, "allow_blank": True}}

    def validate_text(self, value: str) -> str:
        value = value.strip()
        if len(value) < 20:
            raise serializers.ValidationError("The lecture text is too short to work with (at least 20 characters).")
        return value

    def get_characters(self, material: LectureMaterial) -> int:
        return len(material.text)


